function translateType(lang, rawType) {
    if (!rawType) return "";
    var tLow = rawType.toLowerCase();
    if (lang === "en") {
        if (tLow.indexOf("лек") !== -1) return "Lecture";
        if (tLow.indexOf("практ") !== -1) return "Practice";
        if (tLow.indexOf("лаб") !== -1) return "Lab Work";
        if (tLow.indexOf("электр") !== -1) return "Online Lecture";
    } else if (lang === "fr") {
        if (tLow.indexOf("лек") !== -1) return "Cours magistral";
        if (tLow.indexOf("практ") !== -1) return "Travaux dirigés";
        if (tLow.indexOf("лаб") !== -1) return "Travaux pratiques";
        if (tLow.indexOf("электр") !== -1) return "Cours en ligne";
    } else if (lang === "de") {
        if (tLow.indexOf("лек") !== -1) return "Vorlesung";
        if (tLow.indexOf("практ") !== -1) return "Übung";
        if (tLow.indexOf("лаб") !== -1) return "Praktikum";
        if (tLow.indexOf("электр") !== -1) return "Online-Vorlesung";
    }
    return rawType;
}

function formatRoom(lang, room) {
    if (!room) return "";
    var cr = room.trim();
    if (lang === "en") {
        if (cr.indexOf("ауд.") === 0) return "room " + cr.substring(4).trim();
        if (cr.indexOf("ауд") === 0) return "room " + cr.substring(3).trim();
        if (cr.indexOf("Спорт") === 0) return "Gym";
        if (cr.indexOf("Читал") === 0) return "Reading Room";
        return "room " + cr;
    } else if (lang === "fr") {
        if (cr.indexOf("ауд.") === 0) return "salle " + cr.substring(4).trim();
        if (cr.indexOf("ауд") === 0) return "salle " + cr.substring(3).trim();
        if (cr.indexOf("Спорт") === 0) return "Salle de sport";
        if (cr.indexOf("Читал") === 0) return "Salle de lecture";
        return "salle " + cr;
    } else if (lang === "de") {
        if (cr.indexOf("ауд.") === 0) return "Raum " + cr.substring(4).trim();
        if (cr.indexOf("ауд") === 0) return "Raum " + cr.substring(3).trim();
        if (cr.indexOf("Спорт") === 0) return "Sporthalle";
        if (cr.indexOf("Читал") === 0) return "Lesesaal";
        return "Raum " + cr;
    }
    if (cr.indexOf("ауд") === 0 || cr.indexOf("Спорт") === 0 || cr.indexOf("Читал") === 0) {
        return cr;
    }
    return "ауд. " + cr;
}
